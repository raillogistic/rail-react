/**
 * Purpose: Fetch a GraphQL schema from the VITE_API_ENDPOINT in .env and generate TypeScript types
 * Args: None (reads `.env` at project root)
 * Returns: Writes `src/types/schema.ts` to disk
 * Raises: Error when endpoint is missing or network/codegen fails
 * Example: node scripts/generate-schema-types.mjs
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { getIntrospectionQuery, buildClientSchema } from 'graphql';
import dotenv from 'dotenv';
import { codegen } from '@graphql-codegen/core';
import { createRequire } from 'node:module';
const require = createRequire(import.meta.url);
const typescriptPluginModule = require('@graphql-codegen/typescript');
const typescriptResolversPluginModule = require('@graphql-codegen/typescript-resolvers');

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

function read_env_value(env_path, key) {
    /**
     * Purpose: Read a single environment variable from a .env file
     * Args: env_path (string), key (string)
     * Returns: string | undefined env value
     * Raises: None
     * Example: read_env_value('./.env', 'VITE_API_ENDPOINT')
     */
    if (fs.existsSync(env_path)) {
        const content = fs.readFileSync(env_path, 'utf-8');
        const lines = content.split(/\r?\n/);
        for (const line of lines) {
            const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.+?)\s*$/);
            if (m && m[1] === key) {
                return m[2].replace(/^"|"$/g, '').replace(/^'|'$/g, '');
            }
        }
    }
    return undefined;
}

async function fetch_introspection(endpoint_url) {
    /**
     * Purpose: Perform GraphQL introspection query against the endpoint
     * Args: endpoint_url (string)
     * Returns: Introspection JSON (object)
     * Raises: Error on non-200 or network issues
     * Example: await fetch_introspection('http://localhost:8000/graphql/')
     */
    const body = JSON.stringify({ query: getIntrospectionQuery() });
    const res = await fetch(endpoint_url, {
        method: 'POST',
        headers: {
            'content-type': 'application/json',
        },
        body,
    });
    if (!res.ok) {
        const text = await res.text();
        throw new Error(`Introspection failed: ${res.status} ${res.statusText} - ${text}`);
    }
    const json = await res.json();
    if (json.errors) {
        throw new Error(`Introspection returned errors: ${JSON.stringify(json.errors)}`);
    }
    return json.data;
}

async function generate_types(schema, out_path) {
    /**
     * Purpose: Use GraphQL Codegen to emit TypeScript types and resolvers arg types
     * Args: schema (GraphQLSchema), out_path (string)
     * Returns: void (writes file)
     * Raises: Error on codegen failure or write failure
     * Example: await generate_types(schema, 'src/types/schema.ts')
     */
    const plugins = [
        { typescript: {} },
        { typescriptResolvers: { noSchemaStitching: true } },
    ];

    const config = {
        filename: out_path,
        schema: undefined, // we provide schemaAst below
        schemaAst: schema,
        documents: [],
        plugins,
        pluginMap: {
            typescript: typescriptPluginModule,
            typescriptResolvers: typescriptResolversPluginModule,
        },
        config: {
            useTypeImports: true,
            enumsAsTypes: true,
            maybeValue: 'T | null',
            avoidOptionals: true,
            immutableTypes: false,
            scalars: {
                DateTime: 'string',
                Date: 'string',
                JSON: 'Record<string, unknown>',
                Decimal: 'number',
            },
        },
    };

    const output = await codegen(config);
    const header = `// AI-GENERATED: Review required\n// Generated by: generate-schema-types.mjs\n// Purpose: TypeScript types for GraphQL schema (queries, mutations, inputs, enums)\n\n`;
    fs.mkdirSync(path.dirname(out_path), { recursive: true });
    fs.writeFileSync(out_path, header + output, 'utf-8');
}

async function run() {
    /**
     * Purpose: Orchestrate reading endpoint, fetching introspection, building schema, and generating TS types
     * Args: None
     * Returns: void
     * Raises: Error propagated from steps
     * Example: node scripts/generate-schema-types.mjs
     */
    // Load .env for completeness (allows process.env to have values if present)
    dotenv.config({ path: path.resolve(__dirname, '../.env') });
    const env_path = path.resolve(__dirname, '../.env');
    const endpoint = process.env.VITE_API_ENDPOINT || read_env_value(env_path, 'VITE_API_ENDPOINT');
    if (!endpoint) {
        throw new Error('VITE_API_ENDPOINT not found in .env');
    }

    console.log(`[generate-schema-types] Fetching introspection from: ${endpoint}`);
    const introspection = await fetch_introspection(endpoint);
    const schema = buildClientSchema(introspection);

    const out_path = path.resolve(__dirname, '../src/schema.ts');
    await generate_types(schema, out_path);
    console.log(`[generate-schema-types] Wrote TypeScript types to: ${out_path}`);
}

run().catch((err) => {
    console.error('[generate-schema-types] Error:', err);
    process.exitCode = 1;
});